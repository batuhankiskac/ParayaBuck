def test_features_require_annual_h04_and_matching_h03_h05_periods() -> None:
    rows = load_rows()
    assert all(
        row["feature_status"]["h04_asset_growth"]
        in {"READY_SCHEMA_ONLY", "MISSING_INPUT", "BLOCKED_NO_ANNUAL_ASSET_COMPARATOR"}
        for row in rows
    )
    for row in rows:
        income = row["source_lineage"].get("income")
        cfo = row["source_lineage"].get("cfo")
        if row["features"]["h03_accruals"] is not None:
            assert income and cfo
            assert income["period_key"] == cfo["period_key"]
        payout = row["payout_period_key"]
        if row["features"]["h05_net_payout_yield"] is not None:
            assert payout
            assert (
                len({row["source_lineage"][name]["period_key"] for name in ("dividend", "repurchase", "issuance")}) == 1
            )
        if row["features"]["h04_asset_growth"] is not None:
            current_end = row["source_lineage"]["annual_assets"]["period_key"].split("|")[-1]
            prior_end = row["source_lineage"]["previous_assets"]["period_key"].split("|")[-1]
            from datetime import date

            assert 300 <= (date.fromisoformat(current_end) - date.fromisoformat(prior_end)).days <= 430
    for row in rows:
        if row["source_lineage"]["h03_end_assets"] and row["source_lineage"]["h03_begin_assets"]:
            flow_start = row["source_lineage"]["income"]["period_key"].split("|")[-2]
            h03_begin = row["source_lineage"]["h03_begin_assets"]["period_key"].split("|")[-1]
            assert 0 <= (date.fromisoformat(flow_start) - date.fromisoformat(h03_begin)).days <= 7
    for row in rows:
        if row["features"]["h03_accruals"] is not None:
            flow_end = row["source_lineage"]["income"]["period_key"].split("|")[-1]
            flow_start = row["source_lineage"]["income"]["period_key"].split("|")[-2]
            h03_end = row["source_lineage"]["h03_end_assets"]["period_key"].split("|")[-1]
            h03_begin = row["source_lineage"]["h03_begin_assets"]["period_key"].split("|")[-1]
            from datetime import date

            assert h03_end == flow_end
            assert 0 <= (date.fromisoformat(flow_start) - date.fromisoformat(h03_begin)).days <= 7


