def test_source_inventory_reproduces_raw_bytes() -> None:
    if not MANIFEST.is_file():
        pytest.skip("authoritative revision is generated by the targeted command")
    repo = SCRIPT.parents[2]
    manifest = json.loads(MANIFEST.read_text())
    inventory_path = repo / manifest["source_inventory"]
    inventory = json.loads(inventory_path.read_text())
    payload = json.dumps(inventory, sort_keys=True, separators=(",", ":")).encode()
    assert hashlib.sha256(payload).hexdigest() == manifest["source_inventory_sha256"]
    assert inventory == sorted(inventory, key=lambda item: item["relative_path"])
    assert inventory
    for entry in inventory:
        source = repo / entry["relative_path"]
        assert source.is_file()
        assert source.stat().st_size == entry["size"]
        assert hashlib.sha256(source.read_bytes()).hexdigest() == entry["sha256"]
        assert entry["provider"] == "sec_edgar"
        assert entry["kind"] in {"companyfacts", "current_submissions", "archived_submissions"}
