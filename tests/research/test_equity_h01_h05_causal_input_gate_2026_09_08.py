def test_same_span_common_repurchase_blocks_equity_fallback_when_stale() -> None:
    base = {
        "cik": "1",
        "unit": "USD",
        "form": "10-K",
        "start": "2022-01-01",
        "end": "2022-12-31",
        "available_at": "2023-02-01T12:00:00+00:00",
        "normalized_flow_value": 1,
    }
    rows = [
        {**base, "tag": "PaymentsOfDividends", "accn": "div"},
        {**base, "tag": "ProceedsFromIssuanceOfCommonStock", "accn": "iss"},
        {**base, "tag": "PaymentsForRepurchaseOfEquity", "normalized_flow_value": 3, "accn": "equity"},
        {
            **base,
            "tag": "PaymentsForRepurchaseOfCommonStock",
            "available_at": "2024-01-01T12:00:00+00:00",
            "normalized_flow_value": 4,
            "accn": "common-stale",
        },
    ]
    dividend, repurchase, issuance, key = SCRIPT_MODULE.aligned_payout_components(
        rows, cik="1", cutoff="2023-03-01T00:00:00+00:00"
    )
    assert key == "10-K|USD|2022-01-01|2022-12-31"
    assert dividend and dividend["accn"] == "div"
    assert issuance and issuance["accn"] == "iss"
    assert repurchase is None


